func CreateBranch(gitDir string, branchName string, startPoint string, tracking string) error {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	err := seedshell.ImpureRun("git", append(gitArgs, "branch", branchName, startPoint)...)
	if err != nil {
		return seederr.WrapErrorf("failed to create branch %v: %w", branchName, err)
	}
	if tracking != "" {
		err = seedshell.ImpureRun("git", append(gitArgs, "branch", "--set-upstream-to="+tracking, branchName)...)
		if err != nil {
			return seederr.WrapErrorf("failed to set tracking for branch %v: %w", branchName, err)
		}
	}
	return nil
}

func CreateOrphanBranch(gitDir string, branchName string, message string) error {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	// The magic empty tree hash for an orphan git tree.
	// Generated by `git hash-object -t tree /dev/null`
	emptyTree := "4b825dc642cb6eb9a060e54bf8d69288fbee4904"
	rootCommitOutput, err := seedshell.ImpureOutput("git", append(gitArgs, "commit-tree", emptyTree, "-m", message)...)
	if err != nil {
		return seederr.WrapErrorf("failed to create root commit for orphan branch %v: %w", branchName, err)
	}
	rootCommit := strings.TrimSpace(string(rootCommitOutput))
	err = seedshell.ImpureRun("git", append(gitArgs, "branch", branchName, rootCommit)...)
	if err != nil {
		return seederr.WrapErrorf("failed to create orphan branch %v: %w", branchName, err)
	}
	return nil
}

func GetBranch(gitDir string, branchName string) (string, error) {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	branchOutput, err := seedshell.PureOutput("git", append(gitArgs, "rev-parse", "refs/heads/"+branchName)...)
	if err != nil {
		return "", seederr.Wrap(scm.ErrBranchNotFound)
	}
	branch := strings.TrimSpace(string(branchOutput))
	return branch, nil
}

func UpdateBranch(gitDir string, branchName string, newPoint string) error {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	err := seedshell.PureRun("git", append(gitArgs, "branch", "--force", branchName, newPoint)...)
	if err != nil {
		return seederr.Wrap(scm.ErrBranchNotFound)
	}
	return nil
}

func DeleteBranch(gitDir string, branchName string) error {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}

	// An unborn branch has no ref, so git branch --delete fails with "branch not found".
	branchExists := true
	_, err := GetBranch(gitDir, branchName)
	if err != nil {
		if !errors.Is(err, scm.ErrBranchNotFound) {
			return seederr.Wrap(err)
		}
		branchExists = false
	}

	if !branchExists {
		err := seedshell.ImpureRun("git", append(gitArgs, "config", "--remove-section", "branch."+branchName)...)
		if err != nil {
			seedlog.Debugf("No branch configs for unborn branch: %v", branchName)
		}
	} else {
		err := seedshell.ImpureRun("git", append(gitArgs, "branch", "--delete", "--force", branchName)...)
		if err != nil {
			return seederr.WrapErrorf("failed to delete branch %v: %w", branchName, err)
		}
	}

	return nil
}

func DeleteMergedBranch(gitDir string, branchName string) error {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	err := seedshell.ImpureRun("git", append(gitArgs, "branch", "--delete", branchName)...)
	if err != nil {
		return seederr.WrapErrorf("failed to delete branch %v: %w", branchName, err)
	}
	return nil
}

func GetBranchTracking(gitDir string, branchName string) (string, error) {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	trackingBranchOutput, err := seedshell.PureOutput("git", append(gitArgs, "rev-parse", "--abbrev-ref", "--symbolic-full-name", branchName+"@{upstream}")...)
	if err != nil {
		return "", seederr.WrapErrorf("tracking upstream is missing for %v: %w", branchName, err)
	}
	trackingBranch := strings.TrimSpace(string(trackingBranchOutput))
	return trackingBranch, nil
}

func SetBranchTracking(gitDir string, branchName string, tracking string) error {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}

	branchExists := true
	_, err := GetBranch(gitDir, branchName)
	if err != nil {
		if !errors.Is(err, scm.ErrBranchNotFound) {
			return seederr.Wrap(err)
		}
		branchExists = false
	}

	if !branchExists {
		// Unborn branch (e.g. a fresh orphan worktree before its first commit)
		// has no ref, so git branch --set-upstream-to refuses it. Write the
		// tracking config directly, mirroring what --set-upstream-to records: a
		// remote-tracking ref maps to its remote and the branch it mirrors; a
		// local branch maps to remote "." and its own ref.
		fullRefOutput, resolveErr := seedshell.PureOutput("git", append(slices.Clone(gitArgs), "rev-parse", "--symbolic-full-name", tracking)...)
		if resolveErr != nil {
			return seederr.WrapErrorf("failed to resolve tracking ref %v: %w", tracking, resolveErr)
		}
		fullRef := strings.TrimSpace(string(fullRefOutput))

		remote := "."
		merge := fullRef
		if rest, ok := strings.CutPrefix(fullRef, "refs/remotes/"); ok {
			remoteName, mergeBranch, found := strings.Cut(rest, "/")
			if !found {
				return seederr.WrapErrorf("unexpected remote tracking ref %v", fullRef)
			}
			remote = remoteName
			merge = "refs/heads/" + mergeBranch
		}

		err = seedshell.ImpureRun("git", append(slices.Clone(gitArgs), "config", "branch."+branchName+".remote", remote)...)
		if err != nil {
			return seederr.WrapErrorf("failed to set tracking remote for branch %v: %w", branchName, err)
		}
		err = seedshell.ImpureRun("git", append(slices.Clone(gitArgs), "config", "branch."+branchName+".merge", merge)...)
		if err != nil {
			return seederr.WrapErrorf("failed to set tracking merge for branch %v: %w", branchName, err)
		}
	} else {
		// Born branch: point it at its upstream directly.
		err = seedshell.ImpureRun("git", append(gitArgs, "branch", "--set-upstream-to="+tracking, branchName)...)
		if err != nil {
			return seederr.WrapErrorf("failed to set tracking for branch %v: %w", branchName, err)
		}
	}

	return nil
}

func GetMergeBaseHash(gitDir string, base string, target string) (string, error) {
	gitArgs := []string{}
	if gitDir != "" {
		gitArgs = append(gitArgs, "--git-dir", gitDir)
	}
	mergeBaseOutput, err := seedshell.PureOutput("git", append(gitArgs, "merge-base", base, target)...)
	if err != nil {
		return "", seederr.WrapErrorf("failed to get merge base for %v and %v: %w", base, target, err)
	}
	mergeBase := strings.TrimSpace(string(mergeBaseOutput))
	return mergeBase, nil
}
